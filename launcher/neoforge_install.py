"""Prepare NeoForge's Java installer inputs using the launcher's downloader.

The official installer stays byte-for-byte intact. For the supported installer
generation its documented offline mode consumes verified libraries plus a
classpath resource containing official client mappings. That resource is the
same input used by NeoForge's own fat installer, without repacking its JAR.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import tempfile
import zipfile
from contextlib import contextmanager
from pathlib import Path, PurePosixPath
from urllib.parse import urlsplit

from . import lifecycle
from .version_ids import valid

_MAIN = "net.minecraftforge.installer.SimpleInstaller"
_PREFIX = "net/minecraftforge/installer/"
_MAX_JSON = 4 * 1024**2
_MAX_ARTIFACT = 2 * 1024**3
_MAX_LIBRARIES = 1024
_HEX = re.compile(r"[a-fA-F0-9]{40}")
_PART = re.compile(r"[A-Za-z0-9_+.-]{1,180}")
_OFFLINE_INSTALLERS = {"3.0.48"}


def _error(message):
    # Import only on the error path: preparation owns the adapter's lifecycle.
    from .preparation import DownloadError
    return DownloadError("Подготовка зависимостей NeoForge: " + message)


def _json(archive, name):
    try:
        info = archive.getinfo(name)
        if info.is_dir() or not 0 < info.file_size <= _MAX_JSON:
            raise _error("слишком большой или пустой манифест установщика.")
        value = json.loads(archive.read(info))
    except (KeyError, ValueError, RecursionError, zipfile.BadZipFile) as exc:
        raise _error("не удалось прочитать манифест установщика.") from exc
    if not isinstance(value, dict):
        raise _error("неверный формат манифеста установщика.")
    return value


def _relative(value):
    if not isinstance(value, str) or len(value) > 1024:
        raise _error("неверный путь библиотеки.")
    parts = value.split("/")
    if (len(parts) < 3 or any(part in {".", ".."} or not _PART.fullmatch(part) for part in parts)
            or PurePosixPath(value).as_posix() != value):
        raise _error("путь библиотеки выходит за каталог игры.")
    # A colon, backslash, trailing dot, or Windows device name must not become
    # an alternate stream / reserved path when the archive moves to Windows.
    for part in parts:
        stem = part.split(".", 1)[0].upper()
        if part.endswith(".") or stem in {"CON", "PRN", "AUX", "NUL", *("COM" + str(i) for i in range(1, 10)), *("LPT" + str(i) for i in range(1, 10))}:
            raise _error("недопустимое имя библиотеки.")
    return value


def _coordinate(name):
    if not isinstance(name, str):
        raise _error("неверные координаты библиотеки.")
    coordinate, marker, extension = name.partition("@")
    extension = extension if marker else "jar"
    parts = coordinate.split(":")
    if (len(parts) not in (3, 4) or not _PART.fullmatch(extension)
            or any(not _PART.fullmatch(part) or part in {".", ".."} for part in parts)):
        raise _error("неверные координаты библиотеки.")
    group, artifact, version = parts[:3]
    classifier = "-" + parts[3] if len(parts) == 4 else ""
    return _relative(f"{group.replace('.', '/')}/{artifact}/{version}/{artifact}-{version}{classifier}.{extension}")


def _document(archive, minecraft, pin):
    profile = _json(archive, "install_profile.json")
    if (not valid(minecraft) or not valid(pin) or profile.get("spec") != 1
            or profile.get("minecraft") != minecraft or profile.get("version") != "neoforge-" + pin):
        raise _error("версия установщика не совпадает со сборкой.")
    version_path = profile.get("json")
    if not isinstance(version_path, str) or version_path not in {"/version.json", "version.json"}:
        raise _error("неподдерживаемый путь профиля NeoForge.")
    version = _json(archive, version_path.lstrip("/"))
    if version.get("id") != "neoforge-" + pin or version.get("inheritsFrom") != minecraft:
        raise _error("профиль NeoForge не совпадает с версией Minecraft.")
    return profile, version


def _artifacts(profile, version):
    artifacts = {}
    folded = {}
    for document in (profile, version):
        libraries = document.get("libraries")
        if not isinstance(libraries, list) or len(libraries) > _MAX_LIBRARIES:
            raise _error("неверный список библиотек.")
        for library in libraries:
            if not isinstance(library, dict):
                raise _error("неверное описание библиотеки.")
            downloads = library.get("downloads", {})
            if not isinstance(downloads, dict):
                raise _error("неверное описание загрузки библиотеки.")
            artifact = downloads.get("artifact")
            if artifact is None:
                # Outputs generated by processors have no remote artifact.
                continue
            if not isinstance(artifact, dict):
                raise _error("неверное описание файла библиотеки.")
            address = artifact.get("url")
            if address in (None, ""):
                continue
            relative = _relative(artifact.get("path"))
            if relative != _coordinate(library.get("name")):
                raise _error("путь библиотеки не совпадает с её координатами.")
            digest, size = artifact.get("sha1"), artifact.get("size")
            parsed = urlsplit(address) if isinstance(address, str) else None
            if (not isinstance(digest, str) or not _HEX.fullmatch(digest)
                    or type(size) is not int or not 0 < size <= _MAX_ARTIFACT
                    or parsed is None or parsed.scheme != "https" or not parsed.hostname
                    or parsed.username or parsed.password or parsed.query or parsed.fragment
                    or not parsed.path.endswith("/" + relative)):
                raise _error("у библиотеки нет проверяемого адреса, размера или контрольной суммы.")
            candidate = {"path": relative, "url": address, "sha1": digest.lower(), "size": size}
            prior = artifacts.get(relative)
            if prior is not None and prior != candidate:
                raise _error("установщик содержит противоречивые описания библиотеки.")
            case_path = folded.setdefault(relative.casefold(), relative)
            if case_path != relative:
                raise _error("имена библиотек совпадают на Windows.")
            artifacts[relative] = candidate
    return list(artifacts.values())


def installer_artifacts(path, minecraft, pin):
    """Return exact remote artifacts from an already authenticated installer.

    Callers must authenticate the whole JAR against an official digest before
    using this function to authorize imported files. A digest supplied by a ZIP
    sender is not an authority. This parser never accepts imported metadata.
    """
    try:
        with zipfile.ZipFile(path) as archive:
            return _artifacts(*_document(archive, minecraft, pin))
    except (OSError, zipfile.BadZipFile) as exc:
        raise _error("не удалось открыть проверенный установщик.") from exc


def _target(root, relative):
    path = root.joinpath(*relative.split("/"))
    if not path.resolve().is_relative_to(root):
        raise _error("папка библиотеки перенаправлена за пределы игры.")
    for ancestor in (path, *path.parents):
        if ancestor.is_symlink() or getattr(ancestor, "is_junction", lambda: False)():
            raise _error("папка библиотеки перенаправлена.")
        if ancestor == root:
            break
    return path


def _manifest_fields(archive):
    try:
        info = archive.getinfo("META-INF/MANIFEST.MF")
        if info.file_size > 65536:
            return {}
        raw = archive.read(info).decode("utf-8").replace("\r\n ", "").replace("\n ", "")
        return dict(line.split(": ", 1) for line in raw.splitlines() if ": " in line)
    except (KeyError, UnicodeError, ValueError):
        return {}


def _offline_capable(archive, profile):
    fields = _manifest_fields(archive)
    if (fields.get("Main-Class") != _MAIN or fields.get("Implementation-Vendor") != "NeoForge"
            or fields.get("Implementation-Version") not in _OFFLINE_INSTALLERS):
        return False
    # Version pin plus feature checks deliberately avoid assuming that a newer
    # installer retains its current resource/offline contract.
    required = {
        _PREFIX + "SimpleInstaller.class": b"ENABLING OFFLINE MODE",
        _PREFIX + "Downloader$LocalSource.class": b"/maven/",
        _PREFIX + "actions/PostProcessors.class": b"Skipping mojmaps download due to local cache hit.",
    }
    for name, marker in required.items():
        try:
            info = archive.getinfo(name)
            if info.file_size > 1024**2 or marker not in archive.read(info):
                return False
        except KeyError:
            return False
    processors = profile.get("processors")
    if not isinstance(processors, list) or not processors or len(processors) > 64:
        return False
    mappings = False
    for processor in processors:
        if not isinstance(processor, dict):
            return False
        sides = processor.get("sides", ["client", "server"])
        if not isinstance(sides, list):
            return False
        if "client" not in sides:
            continue
        jar, args = processor.get("jar", ""), processor.get("args", [])
        if not isinstance(jar, str) or not isinstance(args, list):
            return False
        group_name = ":".join(jar.split(":")[:2])
        if group_name == "net.neoforged.installertools:installertools":
            if len(args) < 2 or args[0] != "--task":
                return False
            if args[1] == "DOWNLOAD_MOJMAPS":
                if args != ["--task", "DOWNLOAD_MOJMAPS", "--version", profile["minecraft"], "--side", "{SIDE}", "--output", "{MOJMAPS}"]:
                    return False
                mappings = True
            elif args[1] not in {"MCP_DATA", "MERGE_MAPPING"}:
                return False
        elif group_name not in {
            "net.neoforged.installertools:jarsplitter", "net.neoforged:AutoRenamingTool",
            "net.neoforged.installertools:binarypatcher",
        }:
            return False
    data = profile.get("data", {})
    mapping_data = data.get("MOJMAPS", {}) if isinstance(data, dict) else {}
    mapping = mapping_data.get("client") if isinstance(mapping_data, dict) else None
    if mappings:
        if not isinstance(mapping, str) or not mapping.startswith("[") or not mapping.endswith("]"):
            return False
        path = _coordinate(mapping[1:-1])
        if not path.startswith("net/minecraft/client/") or not path.endswith("-mappings.txt"):
            return False
    return mappings


def _minecraft_input(metadata, key):
    downloads = metadata.get("downloads", {})
    entry = downloads.get(key, {}) if isinstance(downloads, dict) else {}
    address = entry.get("url") if isinstance(entry, dict) else None
    parsed = urlsplit(address) if isinstance(address, str) else None
    digest = entry.get("sha1") if isinstance(entry, dict) else None
    size = entry.get("size") if isinstance(entry, dict) else None
    if (parsed is None or parsed.scheme != "https"
            or parsed.netloc not in {"piston-data.mojang.com", "launcher.mojang.com"}
            or parsed.query or parsed.fragment or not isinstance(digest, str) or not _HEX.fullmatch(digest)
            or type(size) is not int or not 0 < size <= _MAX_ARTIFACT):
        raise _error("манифест Minecraft не содержит проверяемый файл " + key + ".")
    return {"url": address, "sha1": digest.lower(), "size": size}


def _verified(path, artifact):
    if not path.is_file() or path.stat().st_size != artifact["size"]:
        return False
    digest = hashlib.sha1()
    with path.open("rb") as source:
        while block := source.read(1024**2):
            lifecycle.check()
            digest.update(block)
    return digest.hexdigest() == artifact["sha1"]


def _fetch(downloader, cache, artifact, relative):
    target = _target(cache, relative)
    downloader(artifact["url"], target, sha1=artifact["sha1"], minecraft_directory=cache)
    lifecycle.check()
    if not _verified(target, artifact):
        raise _error("размер или контрольная сумма не совпали: " + Path(relative).name + ".")
    return target


@contextmanager
def adapt(command, *, downloader, cache, cwd=None):
    """Yield a vendor command after preparing its authenticated dependencies.

    Non-NeoForge commands and unsupported installer generations remain intact.
    NeoForge metadata errors and download failures stop before Java executes.
    """
    if (downloader is None or cache is None or not isinstance(command, (tuple, list))
            or len(command) != 5 or command[1] != "-jar" or command[3] != "--install-client"):
        yield command
        return
    root = Path(cache).resolve()
    if Path(command[4]).resolve() != root:
        raise _error("папка установки не совпадает с папкой игры.")
    installer = Path(command[2]).resolve()
    try:
        archive = zipfile.ZipFile(installer)
    except (OSError, zipfile.BadZipFile):
        # The adapter is also installed around unrelated vendor subprocesses.
        yield command
        return
    with archive:
        if "install_profile.json" not in archive.namelist():
            yield command
            return
        preliminary = _json(archive, "install_profile.json")
        installed = preliminary.get("version")
        if not isinstance(installed, str) or not installed.startswith("neoforge-"):
            yield command
            return
        version, pin = preliminary.get("minecraft"), installed.removeprefix("neoforge-")
        profile, descriptor = _document(archive, version, pin)
        artifacts = _artifacts(profile, descriptor)
        offline = _offline_capable(archive, profile)
        # Java cannot escape a classpath separator embedded in a directory
        # name. Preserve the original -jar command for such user-chosen paths.
        offline = offline and os.pathsep not in str(installer) and os.pathsep not in str(root)

    downloader.progress("Подготовка зависимостей NeoForge · проверяем библиотеки…")
    with lifecycle.Executor(max_workers=4) as executor:
        futures = [executor.submit(_fetch, downloader, root, item, "libraries/" + item["path"]) for item in artifacts]
        try:
            pending = set(futures)
            finished = 0
            while pending:
                lifecycle.check()
                ready = [future for future in pending if future.done()]
                if not ready:
                    lifecycle.wait(0.05)
                    continue
                for future in ready:
                    future.result()
                    pending.remove(future)
                    finished += 1
                    downloader.progress(f"Подготовка зависимостей NeoForge · {finished} / {len(artifacts)}")
        except BaseException:
            executor.shutdown(wait=False, cancel_futures=True)
            raise
    if not offline:
        downloader.progress("Настраиваем NeoForge · запускаем официальный установщик…")
        yield command
        return

    manifest = _target(root, f"versions/{version}/{version}.json")
    if not manifest.is_file() or manifest.stat().st_size > _MAX_JSON:
        raise _error("не найден манифест Minecraft для автономной установки.")
    try:
        metadata = json.loads(manifest.read_bytes())
    except (ValueError, RecursionError) as exc:
        raise _error("не удалось прочитать манифест Minecraft.") from exc
    if not isinstance(metadata, dict) or metadata.get("id") != version:
        raise _error("манифест Minecraft не совпадает со сборкой.")
    client = _minecraft_input(metadata, "client")
    _fetch(downloader, root, client, f"versions/{version}/{version}.jar")
    mappings = _minecraft_input(metadata, "client_mappings")
    downloader.progress("Подготовка mappings Minecraft " + version + "…")
    # Keep a verified persistent copy for the next attempt. Java copies the
    # resource into its own precise processor coordinate before processing.
    mapping_path = _fetch(downloader, root, mappings, f"installer-inputs/{version}/client_mappings.txt")
    _target(root, "installer-inputs").mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".blockharbor-inputs-", dir=root / "installer-inputs") as temporary:
        resources = Path(temporary)
        destination = resources / "maven" / "minecraft" / version / "client_mappings.txt"
        destination.parent.mkdir(parents=True)
        digest = hashlib.sha1()
        with mapping_path.open("rb") as source, destination.open("wb") as target:
            while block := source.read(1024**2):
                lifecycle.check()
                digest.update(block)
                target.write(block)
        if digest.hexdigest() != mappings["sha1"] or destination.stat().st_size != mappings["size"]:
            raise _error("mappings изменились во время подготовки.")
        downloader.progress("Настраиваем NeoForge · все файлы подготовлены, устанавливаем локально…")
        yield [str(command[0]), "-cp", str(installer) + os.pathsep + str(resources), _MAIN,
               "--offline", "--install-client", str(root)]
        lifecycle.check()
